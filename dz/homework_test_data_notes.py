# Подключаем библиотеку csv для работы с CSV-файлами.
import csv

# Подключаем библиотеку json для чтения и записи JSON-файлов.
import json


# -----------------------------
# 1. ЧИТАЕМ ПОЛЬЗОВАТЕЛЕЙ
# -----------------------------

# Открываем файл users.json в режиме чтения.
# "r" = read, то есть чтение.
# encoding="utf-8" указывает кодировку файла.
# with автоматически закроет файл после окончания блока.
with open("users.json", "r", encoding="utf-8") as file:

    # json.load() читает JSON-файл
    # и превращает его в обычные объекты Python.
    # В нашем случае users станет списком пользователей.
    users = json.load(file)


# -----------------------------
# 2. ЧИТАЕМ КНИГИ ИЗ CSV
# -----------------------------

# Открываем books.csv в режиме чтения.
# newline="" рекомендуется использовать при работе с CSV.
with open("books.csv", "r", encoding="utf-8", newline="") as file:

    # DictReader читает CSV и превращает каждую строку
    # в словарь Python.
    #
    # Например:
    # Title,Author,Pages
    #
    # станет:
    # {
    #     "Title": "...",
    #     "Author": "...",
    #     "Pages": "..."
    # }
    reader = csv.DictReader(file)

    # DictReader сам по себе не является обычным списком.
    # Поэтому превращаем его в list,
    # чтобы было удобно обращаться к книгам.
    books = list(reader)


# -----------------------------
# 3. ПОДГОТАВЛИВАЕМ КНИГИ
# -----------------------------

# Создаем пустой список.
# Сюда будем складывать книги уже в нужном формате.
result_books = []


# Перебираем все книги из исходного CSV.
# row на каждом проходе цикла содержит одну книгу.
for row in books:

    # Создаем новый словарь для текущей книги.
    # Оставляем только нужные нам поля.
    book = {

        # Берем значение из колонки Title
        # и записываем его под новым ключом title.
        "title": row["Title"],

        # Берем автора.
        "author": row["Author"],

        # В CSV значение Pages приходит строкой,
        # например "228".
        # int() превращает его в число 228.
        "pages": int(row["Pages"]),

        # Берем жанр книги.
        "genre": row["Genre"]
    }

    # Добавляем подготовленную книгу
    # в общий список result_books.
    result_books.append(book)


# -----------------------------
# 4. ПОДГОТАВЛИВАЕМ ПОЛЬЗОВАТЕЛЕЙ
# -----------------------------

# Создаем пустой список,
# куда будут добавляться подготовленные пользователи.
result_users = []


# Перебираем всех пользователей из users.json.
for user in users:

    # Создаем новый словарь пользователя.
    # Оставляем только те поля,
    # которые нужны по условию домашнего задания.
    result_user = {

        # Имя пользователя.
        "name": user["name"],

        # Пол пользователя.
        "gender": user["gender"],

        # Адрес пользователя.
        "address": user["address"],

        # Возраст пользователя.
        "age": user["age"],

        # Пока создаем пустой список книг.
        # Позже положим сюда книги этого пользователя.
        "books": []
    }

    # Добавляем подготовленного пользователя
    # в общий список.
    result_users.append(result_user)


# -----------------------------
# 5. СЧИТАЕМ КОЛИЧЕСТВО КНИГ
# -----------------------------

# divmod() сразу делает две операции:
#
# len(result_books) // len(result_users)
# — сколько книг гарантированно получит каждый;
#
# len(result_books) % len(result_users)
# — сколько книг останется.
#
# Например:
# 210 книг / 28 пользователей
#
# books_per_user = 7
# extra_books = 14
books_per_user, extra_books = divmod(
    len(result_books),
    len(result_users)
)


# -----------------------------
# 6. РАСПРЕДЕЛЯЕМ КНИГИ
# -----------------------------

# Индекс книги, с которой нужно начинать
# выдачу следующему пользователю.
#
# Сначала начинаем с первой книги,
# поэтому индекс равен 0.
book_index = 0


# enumerate() позволяет одновременно получать:
#
# index — номер пользователя
# user  — самого пользователя
#
# Например:
# index = 0, user = первый пользователь
# index = 1, user = второй пользователь
for index, user in enumerate(result_users):

    # По умолчанию пользователь получает
    # базовое количество книг.
    # В нашем случае это 7.
    books_count = books_per_user

    # После равномерного распределения
    # у нас осталось extra_books книг.
    #
    # Первым пользователям отдаем
    # по одной дополнительной книге.
    if index < extra_books:
        books_count += 1

    # Берем из списка result_books
    # нужный кусок с помощью среза.
    #
    # Например, если:
    # book_index = 0
    # books_count = 8
    #
    # получится:
    #
    # result_books[0:8]
    #
    # то есть первые 8 книг.
    user["books"] = result_books[
        book_index:book_index + books_count
    ]

    # Передвигаем индекс дальше,
    # чтобы следующему пользователю
    # не достались уже использованные книги.
    #
    # Например:
    # было book_index = 0
    # отдали 8 книг
    #
    # станет:
    # book_index = 8
    book_index += books_count


# -----------------------------
# 7. СОЗДАЕМ RESULT.JSON
# -----------------------------

# Открываем result.json в режиме записи.
#
# "w" = write.
#
# Если файла еще нет — Python его создаст.
# Если файл уже есть — его содержимое будет перезаписано.
with open("result.json", "w", encoding="utf-8") as file:

    # json.dump() записывает Python-объект в JSON-файл.
    #
    # result_users — данные, которые записываем.
    # file — куда записываем.
    #
    # ensure_ascii=False
    # позволяет нормально сохранять Unicode-символы.
    #
    # indent=4
    # делает JSON красиво отформатированным.
    json.dump(
        result_users,
        file,
        ensure_ascii=False,
        indent=4
    )


# -----------------------------
# 8. ПРОВЕРЯЕМ RESULT.JSON
# -----------------------------

# По условию задания итоговый JSON
# должен корректно читаться библиотекой json.
#
# Поэтому снова открываем result.json.
with open("result.json", "r", encoding="utf-8") as file:

    # Если файл содержит неправильный JSON,
    # здесь Python выдаст ошибку.
    #
    # Если программа завершилась без ошибки,
    # значит result.json корректный.
    json.load(file)